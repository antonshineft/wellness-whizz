"""Build the molecule pictures of the supplement pages.

    pip install rdkit requests
    python3 scripts/structures/build.py            # every page in structures_map.py
    python3 scripts/structures/build.py <slug> ... # only these pages

For each page in structures_map.py this looks the compound up in PubChem (the structure is taken from there, never
drawn by hand or by an image model), draws it with outline_mol.py into public/images/structures/<slug>.svg, and
rewrites src/structures.ts, the list the site reads. A compound PubChem does not know stops the build.
"""
import json
import sys
import time
import urllib.parse
from pathlib import Path

import requests

HERE = Path(__file__).resolve().parent
ROOT = HERE.parent.parent
sys.path.insert(0, str(HERE))
from outline_mol import svg_for  # noqa: E402
from structures_map import M  # noqa: E402

CACHE = HERE / 'pubchem.json'
HEAD = '''/**
 * The molecule drawn as the big picture of each supplement page (public/images/structures/<slug>.svg).
 * Generated by scripts/structures/build.py; edit scripts/structures/structures_map.py, not this file.
 *
 * Every drawing is made from the compound's structure in PubChem (the US National Institutes of Health's chemical
 * database; `cid` is its record there), never by an image model. `kind` says how the compound relates to the page:
 *   self   - the supplement is this substance
 *   form   - a common supplement form of a mineral (a mineral alone is a single atom)
 *   active - the main studied compound of a plant or extract
 *   part   - a characteristic component of a food, protein, blend or category page
 * Pages without an entry (an enzyme, for example, has no small-molecule structure) keep their earlier picture.
 */
export interface Structure {
  compound: string;
  kind: 'self' | 'form' | 'active' | 'part';
  note: string;
  cid: number;
}

export const STRUCTURES: Record<string, Structure> = {
'''
TAIL = '''};

/** What the picture shows, for the image description: "Molecular structure of withaferin A, the most studied withanolide of ashwagandha". */
export function structureAlt(slug: string, supplementName: string): string | null {
  const s = STRUCTURES[slug];
  if (!s) return null;
  const base = `Molecular structure of ${s.compound}`;
  if (s.kind === 'form') return `${base}, a common supplement form of ${supplementName.toLowerCase()}`;
  return s.note ? `${base}, ${s.note}` : base;
}
'''


def lookup(name: str, cache: dict) -> dict:
    if name not in cache:
        url = 'https://pubchem.ncbi.nlm.nih.gov/rest/pug/compound/name/' + urllib.parse.quote(name) + '/property/SMILES,MolecularFormula,MolecularWeight,Title/JSON'
        r = requests.get(url, timeout=30)
        if r.status_code != 200:
            raise SystemExit(f'PubChem does not know "{name}" (HTTP {r.status_code}); choose another name in structures_map.py')
        p = r.json()['PropertyTable']['Properties'][0]
        cache[name] = {'cid': p['CID'], 'smiles': p.get('SMILES') or p.get('ConnectivitySMILES'), 'formula': p['MolecularFormula'], 'mw': p['MolecularWeight'], 'title': p.get('Title', '')}
        time.sleep(0.25)
    return cache[name]


def main() -> int:
    only = set(sys.argv[1:])
    cache = json.loads(CACHE.read_text()) if CACHE.exists() else {}
    out = ROOT / 'public' / 'images' / 'structures'
    out.mkdir(parents=True, exist_ok=True)
    lines = []
    for slug, (name, kind, note) in sorted(M.items()):
        rec = lookup(name, cache)
        if not only or slug in only:
            (out / f'{slug}.svg').write_text(svg_for(rec['smiles']))
        lines.append(f'  {json.dumps(slug)}: {{ compound: {json.dumps(name)}, kind: {json.dumps(kind)}, note: {json.dumps(note)}, cid: {rec["cid"]} }},')
    CACHE.write_text(json.dumps(cache, indent=1))
    (ROOT / 'src' / 'structures.ts').write_text(HEAD + '\n'.join(lines) + '\n' + TAIL)
    print(f'{len(lines)} pages, pictures in {out}')
    return 0


if __name__ == '__main__':
    sys.exit(main())
