// Writes src/evidence.ts from scripts/evidence/evidence.json: the evidence grade of each graded supplement and the top ten.
//
//   node scripts/evidence/build.cjs
//
// evidence.json is the one table behind the "ranked by evidence" article and the grade badges on supplement pages, so the
// two cannot disagree. Every reference in it was retrieved from PubMed and its numbers copied from the abstract (19 Nov
// 2026). The rule: A, a Cochrane review or two independent meta-analyses of randomised trials agree on an effect that
// matters; B, an effect that is small, inconsistent or limited to a narrow group; C, mixed results; D, mostly null or
// too little trial evidence. Each supplement is graded on the one outcome it has the best evidence for.
const fs = require('fs');
const path = require('path');
const HERE = __dirname;
const data = JSON.parse(fs.readFileSync(path.join(HERE, 'evidence.json'), 'utf8'));
// Positions 1 to 6 are the grade A entries in the order of the table; 7 to 10 were chosen among grade B and approved by the owner.
const TOP = [...data.order_a, 'protein-powder-whey-2d3f0', 'potassium-131fa', 'cranberry-supplements-ab277', 'melatonin'];
const out = {};
for (const s of data.supplements) {
  const rank = TOP.indexOf(s.slug) + 1;
  out[s.slug] = { grade: s.grade, outcome: s.outcome.replace(/\s*\([^)]*\)\s*$/, ''), effect: s.effect_plain, limits: s.limits, pmids: s.refs.map((r) => r.pmid), ...(rank ? { rank } : {}) };
}
fs.writeFileSync(path.join(HERE, '..', '..', 'src', 'evidence.ts'), `/**
 * The evidence grade of each graded supplement, on the one outcome it has the best trial evidence for, and its place in
 * the top ten. Generated by scripts/evidence/build.cjs from scripts/evidence/evidence.json; do not edit.
 */
export interface EvidenceGrade {
  grade: 'A' | 'B' | 'C' | 'D';
  outcome: string;
  effect: string;
  limits: string;
  pmids: string[];
  rank?: number;
}
export const EVIDENCE: Readonly<Record<string, EvidenceGrade>> = ${JSON.stringify(out, null, 1)};
`);
console.log(Object.keys(out).length, 'supplements graded;', TOP.length, 'in the top ten');
