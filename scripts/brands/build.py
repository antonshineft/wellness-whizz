"""Build src/brands-data.ts, the brand profiles shown on /brand/<slug>, from the reviewed files in scripts/brands/data/.

    python3 scripts/brands/build.py

Each data file is one brand: its facts, a short history, and the points for and against it, every point with the
source it rests on. The files are written and checked by hand (see the "reviewed" date in each); nothing is added
here. A logo is used when public/images/brands/ holds a file named after the brand's slug.
"""
import json
import sys
from pathlib import Path

HERE = Path(__file__).resolve().parent
ROOT = HERE.parent.parent
# The order of the strip and the index: the brands with the most picks first.
ORDER = ['now-foods', 'california-gold-nutrition', 'swanson-vitamins', 'nutricost', 'life-extension', 'natural-factors', 'doctors-best', '21st-century',
         'solgar', 'natures-way', 'thorne', 'jarrow-formulas', 'optimum-nutrition', 'solaray', 'source-naturals', 'force-factor']
HEAD = '''/**
 * The brand profiles shown on /brand/<slug>. Generated by scripts/brands/build.py from the reviewed research files
 * in scripts/brands/data/; edit those, not this file.
 */
import type { BrandProfile } from './brands';

export const BRAND_PROFILES: BrandProfile[] = '''


def point(p: dict) -> dict:
    text, source = p['text'].strip(), p['source'].strip()
    if not text or not source.startswith('http'):
        raise SystemExit(f'a point without text or source: {p}')
    return {'text': text, 'source': source, 'sourceName': (p.get('source_name') or p.get('sourceName') or 'Source').strip()}


def main() -> int:
    logos = {f.stem: f.name for f in (ROOT / 'public' / 'images' / 'brands').glob('*') if f.suffix in ('.svg', '.png', '.webp')}
    out = []
    for slug in ORDER:
        f = HERE / 'data' / f'{slug}.json'
        if not f.exists():
            print('no data file for', slug)
            continue
        d = json.loads(f.read_text())
        if not d.get('reviewed'):
            raise SystemExit(f'{slug}: no "reviewed" date; a profile is published only after it has been checked')
        out.append({
            'slug': slug, 'name': d['name'], **({'aliases': d['aliases']} if d.get('aliases') else {}),
            'founded': d.get('founded'), 'founder': d.get('founder'), 'headquarters': d.get('headquarters'), 'owner': d.get('owner'),
            'history': d['history'].strip(),
            'positives': [point(p) for p in d.get('positives', [])], 'negatives': [point(p) for p in d.get('negatives', [])],
            'logo': logos.get(slug), 'reviewed': d['reviewed'],
        })
    (ROOT / 'src' / 'brands-data.ts').write_text(HEAD + json.dumps(out, indent=2, ensure_ascii=False) + ';\n')
    print(f'{len(out)} brands; without a logo: {[b["slug"] for b in out if not b["logo"]]}')
    return 0


if __name__ == '__main__':
    sys.exit(main())
